/** Render text to a canvas mask (white pixels). vertical=true stacks glyphs. */
export function textMask(text, { vertical = false, gap = 1 } = {}) {
  const glyphs = [...text].map((ch) => G5[ch] || G3[ch.toUpperCase()] || G3[' ']);
  const gw = glyphs.map((g) => g[0].length), gh = glyphs.map((g) => g.length);
  const W = vertical ? Math.max(...gw) : gw.reduce((a, b) => a + b + gap, -gap);
  const H = vertical ? gh.reduce((a, b) => a + b + gap, -gap) : Math.max(...gh);
  const cv = makeCanvas(W, H);
  const ctx = cv.getContext('2d');
  ctx.fillStyle = '#fff';
  let ox = 0, oy = 0;
  glyphs.forEach((g, i) => {
    const offX = vertical ? Math.floor((W - gw[i]) / 2) : 0;
    const offY = vertical ? 0 : H - gh[i];
    g.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') ctx.fillRect(ox + offX + x, oy + offY + y, 1, 1); });
    if (vertical) oy += gh[i] + gap; else ox += gw[i] + gap;
  });
  return cv;
}

export function tint(mask, color) {
  const cv = makeCanvas(mask.width, mask.height);
  const ctx = cv.getContext('2d');
  ctx.drawImage(mask, 0, 0);
  ctx.globalCompositeOperation = 'source-in';
  ctx.fillStyle = color;
  ctx.fillRect(0, 0, cv.width, cv.height);
  return cv;
}
